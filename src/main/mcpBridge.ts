/**
 * MCP 桥接：让 Codex、Gemini、Kimi、DeepSeek 这些对话也能用插件提供的 AI 工具。
 *
 * Claude Code 的对话直接走 SDK MCP 通道（control_request: mcp_message），不需要这里。
 * 其他 agent 只认 stdio 的 MCP 服务，所以：
 *   agent 启动 mcp-bridge.cjs（用 Electron 自带的 Node 运行）
 *     → 脚本连上主进程的本地管道（Windows 命名管道 / Unix 套接字），第一行发口令和窗口编号
 *     → 之后原样转发 stdin / stdout 上的 MCP 消息（一行一个 JSON）
 *   主进程在这里处理 initialize / ping，tools/list 和 tools/call 转给对应窗口的界面去执行。
 */
import { app, ipcMain, webContents, type WebContents } from 'electron'
import { randomBytes, timingSafeEqual } from 'node:crypto'
import { promises as fs } from 'node:fs'
import net from 'node:net'
import os from 'node:os'
import path from 'node:path'
import { PANEL_MCP_SERVER } from '../shared/ide'

/** agent 启动的桥接脚本：只负责把 stdio 接到主进程的管道上 */
const SCRIPT = `'use strict'
// Infinite Studio MCP bridge: connects an AI agent's stdio MCP client to the IDE. Generated by the IDE; do not edit.
const net = require('net')
const [addr, auth] = process.argv.slice(2)
const sock = net.connect(addr)
sock.on('connect', () => {
  sock.write(JSON.stringify({ auth }) + '\\n')
  process.stdin.pipe(sock)
  sock.pipe(process.stdout)
})
sock.on('error', (e) => {
  process.stderr.write('Infinite Studio is not reachable: ' + e.message + '\\n')
  process.exit(1)
})
sock.on('close', () => process.exit(0))
process.stdin.on('end', () => sock.end())
`

const INSTRUCTIONS =
  'Tools provided by the Infinite Studio IDE and its plugins. IDE tools give you what the editor knows: getOpenEditors (what the user is looking at), goToDefinition / findReferences / getHover / getDocumentSymbols (language server, precise across files), searchCode (project index, find related code by meaning), getDiagnostics, getGitDiff, getTerminalOutput and runTests. Prefer them over guessing or plain text search when navigating code. Plugin tools (named <plugin>_<action>, e.g. pdf_getText, pptx_addSlide, mindmap_addNodes) work on documents through the editors the user sees in the IDE: binary formats such as PDF and PowerPoint, mind maps, and previews of LaTeX, Markdown and HTML. Changes are saved to disk and can be undone by the user in the editor. Use <plugin>_screenshot to look at the result.'

let server: net.Server | null = null
let address = ''
let secret = ''
let scriptPath = ''
let starting: Promise<void> | null = null

async function ensure(): Promise<void> {
  if (server) return
  if (starting) return starting
  starting = (async () => {
    secret = randomBytes(24).toString('hex')
    const tag = `${process.pid}-${randomBytes(6).toString('hex')}`
    address = process.platform === 'win32' ? `\\\\.\\pipe\\infinite-studio-mcp-${tag}` : path.join(os.tmpdir(), `infinite-studio-mcp-${tag}.sock`)
    scriptPath = path.join(app.getPath('userData'), 'mcp-bridge.cjs')
    const old = await fs.readFile(scriptPath, 'utf8').catch(() => '')
    if (old !== SCRIPT) await fs.writeFile(scriptPath, SCRIPT, 'utf8')
    const srv = net.createServer(onConnection)
    await new Promise<void>((res, rej) => {
      srv.once('error', rej)
      srv.listen(address, () => {
        srv.off('error', rej)
        res()
      })
    })
    server = srv
    app.once('will-quit', () => {
      srv.close()
      if (process.platform !== 'win32') void fs.rm(address, { force: true }).catch(() => undefined)
    })
  })().finally(() => {
    starting = null
  })
  return starting
}

/** 启动桥接脚本的命令（给某个窗口的对话用） */
export async function bridgeCommand(wc: WebContents): Promise<{ command: string; args: string[]; env: Record<string, string> }> {
  await ensure()
  return { command: process.execPath, args: [scriptPath, address, `${secret}:${wc.id}`], env: { ELECTRON_RUN_AS_NODE: '1' } }
}

/** Codex：用 -c 覆盖配置加上这个 MCP 服务（值是 TOML；JSON 字符串和数组也是合法的 TOML） */
export async function codexMcpArgs(wc: WebContents): Promise<string[]> {
  const b = await bridgeCommand(wc)
  const key = `mcp_servers.${PANEL_MCP_SERVER}`
  const env = Object.entries(b.env)
    .map(([k, v]) => `${k}=${JSON.stringify(v)}`)
    .join(',')
  return [
    '-c',
    `${key}.command=${JSON.stringify(b.command)}`,
    '-c',
    `${key}.args=${JSON.stringify(b.args)}`,
    '-c',
    `${key}.env={${env}}`,
    // 编译 LaTeX 之类的工具可能要好几分钟（默认 60 秒）
    '-c',
    `${key}.tool_timeout_sec=900`
  ]
}

/* ---------------- 连接 ---------------- */

function checkAuth(v: unknown): WebContents | null {
  if (typeof v !== 'string') return null
  const i = v.lastIndexOf(':')
  if (i < 0) return null
  const a = Buffer.from(v.slice(0, i))
  const b = Buffer.from(secret)
  if (a.length !== b.length || !timingSafeEqual(a, b)) return null
  const wc = webContents.fromId(Number(v.slice(i + 1)))
  return wc && !wc.isDestroyed() ? wc : null
}

function onConnection(sock: net.Socket): void {
  let buf = ''
  let wc: WebContents | null = null
  sock.setEncoding('utf8')
  sock.on('error', () => undefined)
  const authTimer = setTimeout(() => {
    if (!wc) sock.destroy()
  }, 10_000)
  const send = (msg: Record<string, unknown>): void => {
    if (!sock.destroyed) sock.write(JSON.stringify(msg) + '\n')
  }

  sock.on('data', (chunk: string) => {
    buf += chunk
    if (buf.length > 64 * 1024 * 1024) {
      sock.destroy()
      return
    }
    let i: number
    while ((i = buf.indexOf('\n')) >= 0) {
      const line = buf.slice(0, i).trim()
      buf = buf.slice(i + 1)
      if (!line) continue
      let m: Record<string, unknown>
      try {
        m = JSON.parse(line)
      } catch {
        continue
      }
      if (!wc) {
        wc = checkAuth(m.auth)
        clearTimeout(authTimer)
        if (!wc) {
          sock.destroy()
          return
        }
        continue
      }
      void onRpc(wc, m, send)
    }
  })
  sock.on('close', () => clearTimeout(authTimer))
}

async function onRpc(wc: WebContents, m: Record<string, unknown>, send: (msg: Record<string, unknown>) => void): Promise<void> {
  // 通知和对我们请求的回复：不用处理（这个服务不向客户端发请求）
  if (m.id === undefined || m.id === null || typeof m.method !== 'string') return
  const reply = (body: Record<string, unknown>): void => send({ jsonrpc: '2.0', id: m.id, ...body })
  const p = (m.params ?? {}) as Record<string, unknown>
  try {
    switch (m.method) {
      case 'initialize':
        return reply({
          result: {
            protocolVersion: typeof p.protocolVersion === 'string' ? p.protocolVersion : '2025-06-18',
            capabilities: { tools: {} },
            serverInfo: { name: PANEL_MCP_SERVER, title: 'Infinite Studio', version: app.getVersion() },
            instructions: INSTRUCTIONS
          }
        })
      case 'ping':
        return reply({ result: {} })
      case 'tools/list':
        return reply({ result: { tools: (await ask(wc, 'list', {}, 20_000)) ?? [] } })
      case 'tools/call': {
        const r = await ask(wc, 'call', { name: p.name, arguments: p.arguments ?? {} }, 16 * 60_000)
        return reply({ result: r ?? { content: [{ type: 'text', text: 'No result' }], isError: true } })
      }
      case 'resources/list':
        return reply({ result: { resources: [] } })
      case 'prompts/list':
        return reply({ result: { prompts: [] } })
      default:
        return reply({ error: { code: -32601, message: `Method not found: ${m.method}` } })
    }
  } catch (e) {
    reply({ error: { code: -32603, message: String((e as Error)?.message ?? e) } })
  }
}

/* ---------------- 转给界面执行 ---------------- */

let nextId = 1
const pending = new Map<number, { wc: WebContents; resolve: (v: unknown) => void; reject: (e: Error) => void }>()

function ask(wc: WebContents, method: 'list' | 'call', params: Record<string, unknown>, timeout: number): Promise<unknown> {
  if (wc.isDestroyed()) return Promise.reject(new Error('The IDE window is closed'))
  const id = nextId++
  return new Promise((resolve, reject) => {
    const done = (): void => {
      clearTimeout(timer)
      pending.delete(id)
      if (!wc.isDestroyed()) wc.off('destroyed', gone)
    }
    const gone = (): void => {
      done()
      reject(new Error('The IDE window was closed'))
    }
    const timer = setTimeout(() => {
      done()
      reject(new Error('The IDE did not respond in time'))
    }, timeout)
    wc.once('destroyed', gone)
    pending.set(id, {
      wc,
      resolve: (v) => {
        done()
        resolve(v)
      },
      reject
    })
    wc.send('agentTools:request', id, method, params)
  })
}

/** 正在执行插件工具的窗口：执行期间不让 Chromium 暂停渲染（窗口被挡住或在后台时 requestAnimationFrame 会停，PDF 渲染、截图就卡住） */
const awake = new Map<number, number>()

export function registerMcpBridgeIpc(): void {
  ipcMain.on('agentTools:awake', (e, on: boolean) => {
    const wc = e.sender
    const n = Math.max(0, (awake.get(wc.id) ?? 0) + (on ? 1 : -1))
    if (n) awake.set(wc.id, n)
    else awake.delete(wc.id)
    if (!wc.isDestroyed()) wc.setBackgroundThrottling(n === 0)
  })
  ipcMain.on('agentTools:reply', (e, id: number, result: unknown) => {
    const p = pending.get(Number(id))
    if (p && p.wc === e.sender) p.resolve(result)
  })
  ipcMain.handle('agent:mcpServers', async (e) => {
    try {
      const b = await bridgeCommand(e.sender)
      return [{ name: PANEL_MCP_SERVER, command: b.command, args: b.args, env: Object.entries(b.env).map(([name, value]) => ({ name, value })) }]
    } catch {
      return []
    }
  })
}
